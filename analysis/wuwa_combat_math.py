# §3 抗性分段函数：连续性验证与系数唯一性反解
# ---------------------------------------------------------------------------
def res_multiplier(r):
    if r < 0:
        return 1 - r / 2
    elif r < 0.8:
        return 1 - r
    else:
        return 1 / (1 + 5 * r)


def section_3_resistance():
    banner("§3  抗性分段函数 —— 连续性验证与系数 k=5 的唯一性反解")

    print("""
【公开规则】
    R < 0      :  mult = 1 - R/2
    0 ≤ R < 0.8:  mult = 1 - R
    R ≥ 0.8    :  mult = 1 / (1 + 5R)
""")

    print(SUB)
    print("【连续性验证】（分段函数最容易出设计事故的地方）")
    print(SUB)
    eps = 1e-9
    for bp in (0.0, 0.8):
        left = res_multiplier(bp - eps)
        right = res_multiplier(bp + eps)
        at = res_multiplier(bp)
        ok = "连续 ✓" if abs(left - right) < 1e-6 else "断点 ✗"
        print(f"  R = {bp:.1f} :  左极限 {left:.6f}   右极限 {right:.6f}   取值 {at:.6f}   {ok}")

    print("""
【★ 结论四：系数 5 不是拍脑袋选的，它被连续性条件唯一确定】

  设高抗段形如 1/(1+kR)，要求它在 R=0.8 处与中段 1-R 无缝衔接：
      1 / (1 + 0.8k) = 1 - 0.8 = 0.2
      ==> 1 + 0.8k = 5
      ==> k = 5
  k 无自由度。这说明设计流程是"先定拐点 0.8 与中段线性式，再解出高抗段
  系数"，而不是三段各自调参——一个可以从公开数字反推出来的实现细节。
""")

    # 边际斜率
    print(SUB)
    print("【一阶导（减抗的边际收益）】")
    print(SUB)
    print("""  中段  d(1-R)/dR        = -1
  高抗段 d[1/(1+5R)]/dR    = -5/(1+5R)²，在 R=0.8 处 = -5/25 = -0.2
  负抗段 d(1-R/2)/dR       = -0.5

  函数连续但一阶导不连续。三段斜率 -0.5 / -1 / -0.2 对应三种设计意图：""")

    print(f"""
    · 负抗段斜率减半：减抗堆到负数后收益打对折 —— 对"减抗流"配队的软性
      收益衰减，防止减抗成为无脑最优解。R 从 0 打到 -100% 只拿到
      ×{res_multiplier(-1.0):.2f} 而非 ×2.00。

    · 中段线性：玩家直觉区。"敌人 20% 抗性 = 少 20% 伤害"，所见即所得。

    · 高抗段双曲：伤害倍率恒为正，敌人永不免疫。R=200% 时仍有
      ×{res_multiplier(2.0):.4f}，R=1000% 时 ×{res_multiplier(10.0):.4f}。
      这是一道数值安全阀 —— 设计师可以放心给后期敌人堆高抗做检查点，
      不必担心某个抗性数字把玩家伤害归零、造成不可通关的死局。
""")

    print(SUB)
    print("【抗性 → 伤害倍率曲线】")
    print(SUB)
    print(f"{'抗性 R':>10} {'倍率':>10} {'相对 0 抗':>12}")
    base = res_multiplier(0.0)
    for r in (-1.0, -0.5, -0.2, 0.0, 0.1, 0.2, 0.4, 0.6, 0.79, 0.8, 1.0, 1.5, 2.0, 5.0):
        m = res_multiplier(r)
        print(f"{r:>10.2f} {m:>10.4f} {m / base * 100:>11.1f}%")

    print("""
  实战锚点：大世界怪物基础全抗 10%，对应属性怪额外 +30%（合计 40%）。
  代入中段：打"本属性抗性怪"伤害倍率 0.60，相对打普通怪 0.90 少 33.3%。
  ==> 这是"属性队打对应属性怪反而吃亏"的数值来源，也是驱动玩家养多队
      （而非一队通吃）的经济学杠杆 —— 直接服务角色卡池的宽度消费。
""")


