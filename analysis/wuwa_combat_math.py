    print(SUB)
    print("【验证】CV 相同但配比不同的两套词条，实际暴击乘区差多少？")
    print(SUB)
    print(f"{'配置':>28} {'CR':>8} {'CD':>8} {'CV':>7} {'E':>9} {'相对最优':>9}")
    B = 8 * SUB_CR_AVG
    rows = []
    for n_cr in range(0, 9):
        x = n_cr * SUB_CR_AVG
        cr = BASE_CR + x
        cd = 1 + (BASE_CD - 1) + 2 * (B - x)
        cv = cr * 2 + (cd - 1)
