# ---------------------------------------------------------------------------
# 公开常量
# ---------------------------------------------------------------------------
BASE_CR = 0.05          # 基础暴击率
BASE_CD = 1.50          # 基础暴击伤害（倍数形式，150%）

SUB_CR_MIN, SUB_CR_MAX = 0.063, 0.105      # 副词条暴击率档位区间
SUB_CD_MIN, SUB_CD_MAX = 0.126, 0.210      # 副词条暴击伤害档位区间
SUB_ROLL_TIERS = 8                          # 每种词条的档位数

SUB_CR_AVG = (SUB_CR_MIN + SUB_CR_MAX) / 2
SUB_CD_AVG = (SUB_CD_MIN + SUB_CD_MAX) / 2


def crit_multiplier(cr, cd):
    """暴击期望乘区。cr 会被硬钳制在 100%（游戏内暴击率上限）。"""
    cr = min(cr, 1.0)
    return cr * cd + (1 - cr)


