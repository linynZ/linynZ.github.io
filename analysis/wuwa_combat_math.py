# §1 双爆最优配比：解析解 + 数值验证 + 失效边界
# ---------------------------------------------------------------------------
def section_1_crit_optimum():
    banner("§1  双爆最优配比 —— 解析解、数值验证与社区经验的失效边界")

    print("""
【建模】
  暴击期望乘区  E(CR, CD) = 1 + CR·(CD - 1)
  记 D = CD - 1 为"超出非暴击的净暴伤"，则 E = 1 + CR·D。

  一条副词条的平均贡献：暴击率 +{cr:.4f}，暴击伤害 +{cd:.4f}。
  比值 {ratio:.4f} —— 一条暴伤词条恰好等于两条暴击率词条的数值量。
  据此定义词条预算 B（以"暴击率当量"计），把 B 拆成给暴击率的 x 与给暴伤的 B-x：
      CR = CR0 + x
      D  = D0 + 2(B - x)
""".format(cr=SUB_CR_AVG, cd=SUB_CD_AVG, ratio=SUB_CD_AVG / SUB_CR_AVG))

    print("""【解析求解】
  E(x) = 1 + (CR0 + x)·(D0 + 2B - 2x)
  dE/dx = (D0 + 2B - 2x) - 2(CR0 + x) = 0
      ==>  D0 + 2B - 2x = 2·(CR0 + x)
      ==>  D* = 2·CR*
  二阶导 d²E/dx² = -4 < 0，为极大值。

  ★ 结论一（内点最优条件）：当  CD - 1 = 2 × CR  时暴击期望乘区取极大。
    这就是社区口口相传的"双爆 1:2"——本推导给出了它的数学出处，
    而非经验法则：它成立的前提是"一条暴伤词条 = 两条暴击率词条"这一档位设计。
""")

    # 数值验证：固定总预算，扫描分配比例
    print(SUB)
    print("【数值验证】总词条预算 B = 8 条暴击率当量（≈ 8 条暴击率 或 4 条暴伤）")
    print(SUB)
    B = 8 * SUB_CR_AVG
    print(f"{'给暴击率的条数':>14} {'CR':>9} {'CD':>9} {'暴击乘区E':>11} {'D/CR':>8}")
    best = (None, -1)
    for n_cr in range(0, 9):
        x = n_cr * SUB_CR_AVG
        cr = BASE_CR + x
        d = (BASE_CD - 1) + 2 * (B - x)
        cd = 1 + d
        e = crit_multiplier(cr, cd)
        ratio = d / cr if cr else float("inf")
        mark = ""
        if e > best[1]:
            best = (n_cr, e)
        print(f"{n_cr:>14} {cr:>9.4f} {cd:>9.4f} {e:>11.5f} {ratio:>8.3f}{mark}")
    print(f"\n  数值最优出现在给暴击率 {best[0]} 条处，E = {best[1]:.5f}")

    # 解析最优点
    x_star = ((BASE_CD - 1) + 2 * B - 2 * BASE_CR) / 4
    cr_star = BASE_CR + x_star
    d_star = (BASE_CD - 1) + 2 * (B - x_star)
    print(f"  解析最优点：CR* = {cr_star:.4f}，CD* = {1 + d_star:.4f}，"
          f"验证 D*/CR* = {d_star / cr_star:.4f}（应为 2.000）")

    # 失效边界
    print(SUB)
    print("【★ 结论二：社区经验的失效边界（本拆解案的原创补充）】")
    print(SUB)
    print("""
  上面的解是"内点解"，它默认 CR 可以自由取值。但游戏内暴击率封顶 100%，
  一旦最优解要求的 CR* > 100%，问题就退化成角点解——此时正确策略是
  "把所有词条给暴伤"，而"1:2"反而是错的。

  求临界预算 B_c：令 CR* = 100%
      CR0 + ((CD0-1) + 2B - 2·CR0)/4 = 1
""")
    # 解 B_c
    B_c = (4 * (1 - BASE_CR) - ((BASE_CD - 1) - 2 * BASE_CR)) / 2
    print(f"      ==> B_c = {B_c:.4f} 暴击率当量 = {B_c / SUB_CR_AVG:.1f} 条副词条当量")
    print(f"""
  也就是说：当角色从武器 / 共鸣链 / 声骸主词条 / 队友增益处已经拿到
  约 {B_c / SUB_CR_AVG:.0f} 条词条当量以上的双爆资源时，1:2 配比失效，
  边际决策应全部倒向暴伤。

  这解释了一个玩家侧的常见困惑：为什么部分角色（自带高暴击率共鸣链、
  或搭配暴击率武器时）社区推荐的配装会偏离 1:2 而堆到"暴击率溢出前
  全走暴伤"——不是攻略互相矛盾，是两者处在约束的不同侧。
""")

    # 演示角点解
    print(SUB)
    print("【角点解演示】角色已有额外 +40% 暴击率（武器主词条 + 共鸣链）")
    print(SUB)
    cr_ext = 0.40
    print(f"{'给暴击率的条数':>14} {'CR(钳制后)':>12} {'CD':>9} {'暴击乘区E':>11}")
    best2 = (None, -1)
    for n_cr in range(0, 9):
        x = n_cr * SUB_CR_AVG
        cr_raw = BASE_CR + cr_ext + x
        cr = min(cr_raw, 1.0)
        d = (BASE_CD - 1) + 2 * (B - x)
        e = crit_multiplier(cr, 1 + d)
        if e > best2[1]:
            best2 = (n_cr, e)
        flag = "  <- 暴击率已溢出" if cr_raw > 1.0 else ""
        print(f"{n_cr:>14} {cr:>12.4f} {1 + d:>9.4f} {e:>11.5f}{flag}")
    print(f"\n  最优：给暴击率 {best2[0]} 条（对比无外部暴击率时的 {best[0]} 条）")
    print("  ==> 外部暴击率来源越多，最优解越向「全暴伤」迁移，与解析边界一致。")


