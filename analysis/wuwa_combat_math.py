def section_6_marginal():
    banner("§6  边际收益敏感度 —— 给定当前面板，下一条词条应该要什么")

    print("""
【方法】固定其余乘区，比较单条词条带来的总伤害相对增量：
    · 暴击率 +8.40%      （档位中值）
    · 暴击伤害 +16.80%   （档位中值）
    · 攻击力 +8.60%      （按副词条攻击力% 档位中值估）
    · 属性伤害加成 +8.60%（与攻击力同量级，但落在增伤区）

  注意攻击力落在**基数区**、伤害加成落在**增伤区**、双爆落在**暴击区**，
  三者互为乘算 —— 因此边际收益取决于各自区内已堆叠的存量（收益递减）。
""")

    scenarios = [
        ("裸装新号",     0.05, 1.50, 1.00, 0.00),
        ("成长期",       0.35, 1.80, 1.60, 0.30),
        ("成型队",       0.65, 2.20, 2.20, 0.60),
        ("满配毕业",     0.80, 2.60, 2.60, 0.90),
        ("暴击率溢出",   0.95, 2.40, 2.40, 0.80),
    ]

    sub_atk = 0.086
    sub_dmg = 0.086

    print(SUB)
    print(f"{'场景':>12} {'CR':>6} {'CD':>6} {'攻击区':>7} {'增伤区':>7} "
          f"{'ΔCR':>8} {'ΔCD':>8} {'Δ攻击':>8} {'Δ增伤':>8} {'最优':>10}")
    print(SUB)

    for name, cr, cd, atk_mult, dmg_bonus in scenarios:
        base = crit_multiplier(cr, cd) * atk_mult * (1 + dmg_bonus)

        g_cr = crit_multiplier(cr + SUB_CR_AVG, cd) * atk_mult * (1 + dmg_bonus) / base - 1
        g_cd = crit_multiplier(cr, cd + SUB_CD_AVG) * atk_mult * (1 + dmg_bonus) / base - 1
        g_atk = crit_multiplier(cr, cd) * (atk_mult + sub_atk) * (1 + dmg_bonus) / base - 1
        g_dmg = crit_multiplier(cr, cd) * atk_mult * (1 + dmg_bonus + sub_dmg) / base - 1

        opts = {"暴击率": g_cr, "暴伤": g_cd, "攻击力": g_atk, "增伤": g_dmg}
        best = max(opts, key=opts.get)

        print(f"{name:>12} {cr:>6.2f} {cd:>6.2f} {atk_mult:>7.2f} {dmg_bonus:>7.2f} "
              f"{g_cr * 100:>7.2f}% {g_cd * 100:>7.2f}% {g_atk * 100:>7.2f}% "
              f"{g_dmg * 100:>7.2f}% {best:>10}")

    print("""
【★ 结论七：词条优先级不是一张静态表，而是面板的函数】

  多数攻略给出的"暴击率 > 暴击伤害 > 攻击% ≈ 增伤"是一个**平均意义上的
  近似**，它只在成长期区间成立：
    · 裸装期，暴击率的边际收益最高（基数 5% 时每一点都在撬动整个乘区）
    · 成型后，最优项随双爆存量迁移，且一旦暴击率接近封顶，
      它的边际收益断崖式归零（见"暴击率溢出"行）
    · 攻击力与增伤的边际收益只取决于**各自区内的存量**，与双爆无关 ——
      因此"堆到某个区特别高"永远是次优解，乘区结构天然奖励均衡

  ==> 作为策划的读法：这套乘区设计把"配装"变成了一个**每个人答案都不同
      的局部优化问题**，而不是一张可以抄的标准答案表。攻略的存在价值被
      从"给答案"改成了"给方法"，社区讨论的生命周期因此被拉长。
      这是数值结构对社区生态的隐性设计。
""")


