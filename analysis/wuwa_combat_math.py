def def_multiplier(lv_atk, lv_target, def_target=None, ignore=0.0):
    """防御乘区。def_target 缺省时用社区通行的怪物防御拟合式。"""
    if def_target is None:
        # 简化式：(100 + L_char) / (199 + L_mob + L_char)
        return (100 + lv_atk) / (199 + lv_target + lv_atk)
    return (800 + 8 * lv_atk) / (800 + 8 * lv_atk + def_target * (1 - ignore))


def def_multiplier_genshin(lv_atk, lv_target):
    """原神防御乘区（公开公式），用于跨产品同构性对照。"""
    return (lv_atk + 100) / (lv_atk + lv_target + 200)


def section_4_level_suppression():
    banner("§4  等级压制曲线 —— 一个否定性发现：防御区不是差异化设计点")

    print("""
【公开公式】
    鸣潮 防御乘区 = (800 + 8·L_攻) / (800 + 8·L_攻 + DEF_目标·(1 - 无视防御))
    社区通行简化式（怪物防御按等级拟合后）：
         鸣潮 ≈ (100 + L_角色) / (199 + L_怪物 + L_角色)
         原神 =  (100 + L_角色) / (200 + L_怪物 + L_角色)

【★ 首先要说的是一个我自己推翻掉的假设】

  本拆解案初稿曾写下"鸣潮的等级压制显著温和于原神，因此把门槛从练度
  转移到了操作"。落笔前把两个公式并排代入，结论被自己证伪：
  两式分母仅差 1，是同一个函数。下面用数值逐点验证。
""")

    print(SUB)
    print("【角色 90 级，怪物等级变化 —— 鸣潮 vs 原神 逐点对照】")
    print(SUB)
    lv_c = 90
    print(f"{'怪物等级':>10} {'等级差':>8} {'鸣潮':>10} {'原神':>10} {'两者之差':>10} "
          f"{'鸣潮相对同级':>14}")
    ref_w = def_multiplier(lv_c, lv_c)
    max_gap = 0.0
    for lv_m in range(70, 121, 5):
        mw = def_multiplier(lv_c, lv_m)
        mg = def_multiplier_genshin(lv_c, lv_m)
        max_gap = max(max_gap, abs(mw - mg))
        print(f"{lv_m:>10} {lv_m - lv_c:>+8} {mw:>10.4f} {mg:>10.4f} "
              f"{abs(mw - mg):>10.5f} {mw / ref_w * 100:>13.2f}%")

    print(f"\n  两条曲线的最大偏差：{max_gap:.5f}（{max_gap * 100:.3f} 个百分点）")

    print(SUB)
    print("【每级边际强度对照】")
    print(SUB)
    print(f"{'':>14} {'90 vs 90':>12} {'90 vs 91':>12} {'每级衰减':>12}")
    for name, fn in (("鸣潮", def_multiplier), ("原神", def_multiplier_genshin)):
        a = fn(90, 90)
        b = fn(90, 91)
        print(f"{name:>14} {a:>12.5f} {b:>12.5f} {(b / a - 1) * 100:>11.3f}%")

    print("""
【★ 结论五（否定性结论）：防御乘区是被两家共享的行业标准解，
    等级压制强度实质相同 —— 这里没有产品差异化】""")

    m_same = def_multiplier(90, 90)
    m_p10 = def_multiplier(90, 100)
    m_m10 = def_multiplier(90, 80)
    print(f"""
  · 同级（90 vs 90）：防御乘区 {m_same:.4f}
  · 越级 10 级（90 vs 100）：{m_p10:.4f}，损失 {(1 - m_p10 / m_same) * 100:.2f}%
  · 碾压 10 级（90 vs 80）：{m_m10:.4f}，增益 {(m_m10 / m_same - 1) * 100:.2f}%
  · 原神在同样条件下的三个数字：{def_multiplier_genshin(90, 90):.4f} /
    {def_multiplier_genshin(90, 100):.4f} / {def_multiplier_genshin(90, 80):.4f}

  两者每级衰减都在 0.26% 量级，等级差 ±10 只带来约 ±2.5% 的伤害摆动。
  也就是说，"练度不够打不动"这一常见体验**不来自防御乘区**。

  这个否定性结论有两点用处：

  (1) 纠正一个流行的归因错误。玩家侧常把越级挑战的吃力归咎于"等级压制"，
      但防御区在两款产品里都温和到可以忽略。真正的练度门槛来自另外两处：
      角色等级带来的**攻击力面板成长**（进入基数区，是乘区里权重最大的
      一项），以及敌人**血量随等级的成长**（不在伤害公式内，但直接决定
      击杀所需回合数）。策划做数值时若混淆这三者，会把调参调在错误的
      旋钮上。

  (2) 反向界定了鸣潮真正的差异化位置。既然防御区被抄作业式地共享，
      那么它与同赛道产品的区别必然落在别处 —— 从本拆解案的其余章节看，
      落在**抗性段函数的钳制方式**（§3）、**随机性在养成链上的位置**
      （§5，筛选制 vs 强化制）、以及**协奏值把切人资源化**（正文 §3）。
      这三处才是值得展开的设计选择。

  方法论备注：拆解案里敢于写"这里没有特殊设计"，比给每个数字都硬编一个
  设计意图更接近真实的策划工作。数值系统里存在大量行业沿用解，识别出
  哪些是沿用、哪些是选择，本身就是拆解能力的一部分。
""")

