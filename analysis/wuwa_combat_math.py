SUBSTAT_POOL = [
    "暴击率", "暴击伤害",
    "攻击力%", "攻击力(数值)",
    "生命值%", "生命值(数值)",
    "防御力%", "防御力(数值)",
    "共鸣效率",
    "普攻伤害加成", "重击伤害加成",
    "共鸣技能伤害加成", "共鸣解放伤害加成",
]


def section_5_echo_probability():
    banner("§5  声骸词条命中率 —— 超几何模型与期望毕业成本")

    n_pool = len(SUBSTAT_POOL)
    n_slots = 5
    print(f"""
【建模假设（须以实测校验，见拆解案 §7 待实测清单）】
  · 副词条池按社区通行的 {n_pool} 种建模：{', '.join(SUBSTAT_POOL)}
  · 5 条副词条互不重复 —— 因此是**不放回抽样**，服从超几何分布，
    而非许多攻略文默认的二项分布（后者会系统性高估双爆同出概率）。
  · 本节先按等概率建模求出上界，实测概率非均匀时结论只会更差。
""")

    print(SUB)
    print("【双爆词条命中分布】P(5 条副词条中恰好含 k 条双爆)")
    print(SUB)
    total = comb(n_pool, n_slots)
    print(f"{'k':>4} {'组合数':>10} {'概率':>10} {'累积(≥k)':>12}")
    probs = {}
    for k in range(0, 3):
        c = comb(2, k) * comb(n_pool - 2, n_slots - k)
        probs[k] = c / total
    for k in range(0, 3):
        cum = sum(probs[j] for j in range(k, 3))
        print(f"{k:>4} {comb(2, k) * comb(n_pool - 2, n_slots - k):>10} "
              f"{probs[k] * 100:>9.2f}% {cum * 100:>11.2f}%")
    print(f"\n  校验：Σ = {sum(probs.values()):.6f}（应为 1）")

    p_double = probs[2]
    print(f"""
  ★ 双爆同出概率 {p_double * 100:.2f}%，期望 {1 / p_double:.1f} 个声骸出 1 个。
""")

    print(SUB)
    print("【4C 完美毕业件的期望成本】")
    print(SUB)
    print("""  一件"可用的 4C 主 C 声骸"需要同时满足：
    (1) 套装正确
    (2) 主词条为暴击率或暴伤（4C 随机主词条 6 选 1 中的 2 种）
    (3) 副词条含双爆（且主词条已占其一时，池中相应减少）
""")
    p_set = 1 / 5          # 无定向假设（保守上界）；定向刷怪下显著更高
    p_main = 2 / 6         # 6 种随机主词条中命中双爆之一
    # 主词条已占一个双爆，副词条池中该词条被排除
    pool_after_main = n_pool - 1
    p_other_crit_in_subs = 1 - comb(pool_after_main - 1, n_slots) / comb(pool_after_main, n_slots)

    print(f"  P(套装) = {p_set:.4f}   （无定向假设的保守上界，敏感度见下表）")
    print(f"  P(主词条命中双爆) = {p_main:.4f}")
    print(f"  P(副词条含另一个双爆 | 主词条已占一个) = {p_other_crit_in_subs:.4f}")
    p_all = p_set * p_main * p_other_crit_in_subs
    print(f"\n  P(全部命中) = {p_all:.5f}   ==>  期望 {1 / p_all:.1f} 件 4C 声骸")

    print(f"""
  再叠加"档位要落在高档"这一层：若要求两条双爆均落在 8 档中的高 3 档，
  概率再乘 (3/8)² = {(3 / 8) ** 2:.4f}
      ==> 期望 {1 / (p_all * (3 / 8) ** 2):.0f} 件。

  【P(套装) 敏感度】游戏支持定向刷怪（怪物图鉴即掉落表），1/5 是
  无定向保守上界 [实测校验项：定向刷取的套装命中率]：""")
    for ps, tag in ((1 / 5, "无定向（上界）"), (1 / 3, "弱定向"), (1 / 2, "强定向")):
        pa = ps * p_main * p_other_crit_in_subs
        print(f"    P(套装)={ps:.3f} {tag:>10}  期望 {1 / pa:>6.1f} 件"
              f"   加档位要求 {1 / (pa * (3 / 8) ** 2):>7.1f} 件")
    print(f"""

【★ 结论六：养成系统的随机性预算被刻意压在"筛选"而非"强化"】

  声骸不能重洗、不能定向强化，随机性 100% 在掉落瞬间结算完毕。
  它带来一个反直觉的体验优势：**沉没成本为零**。玩家看一眼副词条即可
  当场判弃，不会像强化制那样"已经投入了资源，只好继续赌"。

  代价是刷取次数的方差极大（上表的期望值背后是长尾分布），所以库洛必须
  用另外两个设计来兜底：
    · 声骸掉落与大世界怪物强绑定、刷取无体力硬门槛（把"次数"变便宜）
    · 数据坞的"吸收即可合成"（把保底做在合成侧而非强化侧）
  ==> 三者是一套的：不可重洗 → 必须高频刷 → 必须去掉刷取摩擦。
      单看任何一条都会误判为"设计缺陷"，合起来看才是完整的成本结构。
""")


