# §3 44111 的成立临界条件
# ---------------------------------------------------------------------------
def section_3_threshold():
    banner("§3  那 44111 什么时候才成立？—— 求临界条件")

    print("""
  §2 用的是"两个 3C 都取属性伤害加成"这一最优前提。但现实里有两种情况会
  让 43311 的增伤优势缩水：

    (a) 玩家手上没有对应属性的 3C 声骸（属伤主词条本身是随机的）
    (b) 角色的增伤区已经被队友 buff / 武器 / 套装堆得很高（收益递减）

  下面求：**队友已提供多少增伤时，44111 才追平 43311？**
""")

    print(SUB)
    print(f"{'队友提供增伤':>12} {'43311 伤害':>12} {'44111 伤害':>12} {'差距':>10} {'胜者':>8}")
    print(SUB)

    cr_ext, cd_ext = 0.30, 0.60   # 典型成型面板的副词条贡献

    def gap(ext):
        return (total_dmg(*build_panel("43311", cr_ext, cd_ext, dmg_ext=ext))
                - total_dmg(*build_panel("44111", cr_ext, cd_ext, dmg_ext=ext)))

    for ext in [x / 100 for x in range(0, 301, 25)]:
        r43 = total_dmg(*build_panel("43311", cr_ext, cd_ext, dmg_ext=ext))
        r44 = total_dmg(*build_panel("44111", cr_ext, cd_ext, dmg_ext=ext))
        win = "43311" if r43 >= r44 else "44111"
        print(f"{ext * 100:>11.0f}% {r43:>12.4f} {r44:>12.4f} "
              f"{(r43 / r44 - 1) * 100:>9.2f}% {win:>8}")

    # 二分求交叉点
    lo, hi = 0.0, 3.0
    for _ in range(60):
        mid = (lo + hi) / 2
        if gap(mid) > 0:
            lo = mid
        else:
            hi = mid
    cross = (lo + hi) / 2

    print(f"""
  ★ 二分求得交叉点：外部增伤 = {cross * 100:.1f}%
    低于此值 43311 胜，高于此值 44111 胜。

【★ 结论三：44111 确实有成立区间，但它由"队伍环境"而非"个人偏好"决定】

  这个交叉点的存在，本身就是乘区规律的又一次体现：
  43311 的两个 3C 属伤是**加算进增伤区**的。当队友已经把增伤区堆到
  {cross * 100:.0f}% 以上，再往这个区里加 60% 的边际收益已经很薄；
  而 44111 的暴击率进入的是相对空的暴击区，仍在线性生效。

  于是配装的正确答案取决于**队友是谁**：

    · 单人 / 弱增伤队（如纯输出双 C）→ 增伤区空 → 43311
    · 带强增伤辅助的成型队（增伤 buff 叠满）→ 增伤区饱和 → 44111 反超

  ==> 这解释了社区两种配置长期并存却谁也说服不了谁的原因：
      **双方讨论的其实是不同的队伍环境**，而攻略往往只给结论不给前提。
      一个负责任的攻略应该写成"当队伍增伤总量低于约 {cross * 100:.0f}% 时用 43311"，
      而不是"主流用 43311"。

  作为策划的读法：当一个构筑决策的最优解依赖于**队伍中其他成员的配置**时，
  这个系统就具备了配队深度 —— 但前提是玩家能感知到这层依赖。
  鸣潮在 UI 上完全没有暴露"当前增伤区总量"，玩家无从判断自己在交叉点的哪一侧，
  这层深度因此大部分被浪费掉了（见 §5 改进建议）。
""")

    print(SUB)
    print("【第二个成立条件：资产约束】")
    print(SUB)
    print("""
  除了队伍环境，44111 还有一个更常见的成立场景 —— 玩家手上根本没有
  对味的 3C 属伤声骸（3C 主词条随机，且必须匹配角色属性）。
  此时真实的选择不是"43311 vs 44111"，而是
  "44111  vs  43311 但两个 3C 是废主词条（共鸣效率 / 防御%）"。
""")

    print(SUB)
    print("【验证上述解释】把 43311 的两个 3C 换成废主词条再比一次")
    print(SUB)

    def build_43311_bad(cr_ext, cd_ext):
        cr, cd = BASE_CR + cr_ext, BASE_CD + cd_ext
        cd += MAIN_STAT[4]["暴击伤害"]
        dmg = 0.0                                   # 3C 主词条废掉，不进增伤区
        atk = 1.0 + 2 * MAIN_STAT[1]["攻击力%"]
        return cr, cd, dmg, atk

    print(f"{'副词条双爆':>18} {'43311(废3C)':>14} {'44111':>12} {'胜者':>8}")
    for label, ce, cde in [("+15/30%", 0.15, 0.30), ("+30/60%", 0.30, 0.60),
                           ("+45/90%", 0.45, 0.90)]:
        bad = total_dmg(*build_43311_bad(ce, cde))
        r44 = total_dmg(*build_panel("44111", ce, cde))
        print(f"{label:>18} {bad:>14.4f} {r44:>12.4f} "
              f"{'44111' if r44 > bad else '43311':>8}")

    print("""
  一旦 3C 主词条对不上属性，44111 立刻反超。这印证了上面的判断：
  44111 的存在意义完全由"有没有对味的 3C"决定，与构筑偏好无关。
""")


