"""
《鸣潮》声骸系统拆解案 —— COST 预算组合优化与刷取成本建模
作者：赵鹏淦 (Penggan Zhao)

本脚本的推导对象是声骸系统里唯一一个**构筑决策**：COST 12 的预算怎么花。
社区把它简化成"43311 还是 44111"两句口诀，本脚本把它当成一个带约束的
组合优化问题穷举求解，并给出两种配置各自的成立条件。

公开原材料：COST 预算 12、5 槽位、声骸 COST ∈ {1,3,4}、各 COST 层的主词条池
本脚本推导：可行域穷举、两种主流配置的乘区收益对比、44111 的成立临界条件、
            无体力刷取的时间成本模型

注：主词条满级数值标注 [需核验]，取社区通行值。脚本对数值做了参数化，
    §3 的结论形态（存在临界点、临界点由增伤存量决定）不依赖具体取值。
"""

from itertools import combinations_with_replacement

SEP = "=" * 78
SUB = "-" * 78


def banner(t):
    print("\n" + SEP)
    print(t)
    print(SEP)


# ---------------------------------------------------------------------------
# 公开原材料
# ---------------------------------------------------------------------------
COST_BUDGET = 12
SLOTS = 5
COST_TYPES = (1, 3, 4)

# 各 COST 层主词条满级数值 [需核验，社区通行值]
MAIN_STAT = {
    4: {"暴击率": 0.220, "暴击伤害": 0.440, "攻击力%": 0.330,
        "生命值%": 0.330, "防御力%": 0.418, "治疗效果": 0.264},
    3: {"属性伤害加成": 0.300, "共鸣效率": 0.320, "攻击力%": 0.300,
        "生命值%": 0.300, "防御力%": 0.380},
    1: {"攻击力%": 0.180, "生命值%": 0.228, "防御力%": 0.180},
}

BASE_CR, BASE_CD = 0.05, 1.50


def crit_mult(cr, cd):
    return min(cr, 1.0) * cd + (1 - min(cr, 1.0))


# ---------------------------------------------------------------------------
# §1 可行域穷举
# ---------------------------------------------------------------------------
def section_1_feasible():
    banner("§1  COST 预算的可行域 —— 穷举而非背口诀")

    print(f"""
【约束】恰好装满 {SLOTS} 个槽位，Σ COST ≤ {COST_BUDGET}，单件 COST ∈ {COST_TYPES}

  这是一个带等式约束（槽位数）与不等式约束（预算）的整数组合问题。
  穷举全部 multiset：
""")

    feasible, infeasible = [], []
    for combo in combinations_with_replacement(COST_TYPES, SLOTS):
        total = sum(combo)
        tag = "".join(str(c) for c in sorted(combo, reverse=True))
        (feasible if total <= COST_BUDGET else infeasible).append((tag, total, combo))

    def counts(combo):
        return (combo.count(4), combo.count(3), combo.count(1))

    def dominates(a, b):
        """A 支配 B：A 在 4C/3C 数量上均不少于 B，且至少一项更多。
        （1C 是保底层，不计入支配判定 —— 它永远能被填满）"""
        ca, cb = counts(a)[:2], counts(b)[:2]
        return all(x >= y for x, y in zip(ca, cb)) and ca != cb

    pareto = []
    for tag, total, combo in feasible:
        if not any(dominates(other, combo) for _, _, other in feasible):
            pareto.append(tag)

    print(f"{'配置':>10} {'ΣCOST':>7} {'预算余量':>9} {'4C':>5} {'3C':>5} {'1C':>5} {'状态':>16}")
    print(SUB)
    for tag, total, combo in sorted(feasible, key=lambda x: -x[1]):
        n4, n3, n1 = counts(combo)
        slack = COST_BUDGET - total
        state = "★ Pareto 前沿" if tag in pareto else "被支配，剔除"
        print(f"{tag:>10} {total:>7} {slack:>9} {n4:>5} {n3:>5} {n1:>5} {state:>16}")

    print(f"\n  可行 {len(feasible)} 种，不可行 {len(infeasible)} 种"
          f"（如 44311={4 + 4 + 3 + 1 + 1} > {COST_BUDGET}）")
    print(f"  Pareto 前沿：{', '.join(sorted(pareto, reverse=True))}")

    print("""
【★ 结论一：不被支配的配置有三个，不是社区常说的两个】

  支配判据：若配置 A 在 4C 与 3C 的数量上都不少于 B 且至少一项更多，
  则 B 可被无条件剔除（1C 是保底层，永远填得满，不参与判定）。

  穷举结果留下三个 Pareto 前沿点：

    · 43311（Σ=12，用满预算）：1 个 4C + 2 个 3C —— 社区主流
    · 44111（Σ=11，浪费 1 点）：2 个 4C —— 社区次流
    · 33311（Σ=11，浪费 1 点）：3 个 3C —— **社区几乎不讨论**

  33311 值得单独指出：它不被 43311 支配（3C 更多），却在攻略里长期缺席。
  §2 会把三者一起算。一个配置"没人用"与"不该用"是两件事，
  拆解时先穷举可行域再谈优劣，能避免把社区习惯误当成设计约束。

  另外，预算 12 恰好卡在 43311(=12) 可行、44311(=13) 不可行之间。
  若预算放宽到 13，双 4C 将不再有机会成本，构筑决策会立刻塌缩成
  "能上双 4C 就上"。12 这个数字是为了保住取舍而挑的。
""")


# ---------------------------------------------------------------------------
# §2 两种配置的乘区收益对比
# ---------------------------------------------------------------------------
def build_panel(config, cr_ext=0.0, cd_ext=0.0, dmg_ext=0.0, atk_ext=1.0):
    """按配置返回 (暴击率, 暴伤, 增伤区, 攻击区倍数)。
    43311: 4C 取暴伤，两个 3C 取属伤，两个 1C 取攻击%
    44111: 4C 分别取暴击率与暴伤，三个 1C 取攻击%
    """
    cr, cd = BASE_CR + cr_ext, BASE_CD + cd_ext
    dmg = dmg_ext
    atk = atk_ext

    if config == "43311":
        cd += MAIN_STAT[4]["暴击伤害"]
        dmg += 2 * MAIN_STAT[3]["属性伤害加成"]
        atk += 2 * MAIN_STAT[1]["攻击力%"]
    elif config == "44111":
        cd += MAIN_STAT[4]["暴击伤害"]
        cr += MAIN_STAT[4]["暴击率"]
        atk += 3 * MAIN_STAT[1]["攻击力%"]
    elif config == "33311":
        dmg += 3 * MAIN_STAT[3]["属性伤害加成"]
        atk += 2 * MAIN_STAT[1]["攻击力%"]
    else:
        raise ValueError(config)
    return cr, cd, dmg, atk


CONFIGS = ("43311", "44111", "33311")


def total_dmg(cr, cd, dmg, atk):
    return crit_mult(cr, cd) * (1 + dmg) * atk


def section_2_compare():
    banner("§2  43311 vs 44111 —— 用乘区结构裁决，而不是靠感觉")

    print("""
【建模】只比较受配置影响的三个乘区，其余（倍率区/加深区/防御区/抗性区）
        在两种配置下相同，可约去。

    相对伤害 = 暴击区 × 增伤区 × 攻击区

  三种配置的资源投向：
    43311  1 个 4C 双爆 + 2 个 3C 属伤（+60% 增伤）
    44111  2 个 4C 双爆 + 0 个 3C      （增伤区空置）
    33311  0 个 4C      + 3 个 3C 属伤（+90% 增伤）
""")

    print(SUB)
    print("【基准场景】副词条与武器提供的额外双爆，逐档扫描")
    print(SUB)
    print(f"{'副词条+武器提供':>18} {'配置':>8} {'CR':>7} {'CD':>7} {'增伤':>7} "
          f"{'攻击区':>7} {'相对伤害':>10} {'对比最优':>10}")

    scenarios = [
        ("无额外双爆",        0.00, 0.00),
        ("+15% CR / +30% CD", 0.15, 0.30),
        ("+30% CR / +60% CD", 0.30, 0.60),
        ("+45% CR / +90% CD", 0.45, 0.90),
        ("+60% CR / +120% CD", 0.60, 1.20),
    ]

    win_count = {c: 0 for c in CONFIGS}
    for label, cr_ext, cd_ext in scenarios:
        results = {}
        for cfg in CONFIGS:
            cr, cd, dmg, atk = build_panel(cfg, cr_ext, cd_ext)
            results[cfg] = (cr, cd, dmg, atk, total_dmg(cr, cd, dmg, atk))
        best = max(results, key=lambda c: results[c][4])
        win_count[best] += 1
        best_val = results[best][4]
        for i, cfg in enumerate(CONFIGS):
            cr, cd, dmg, atk, d = results[cfg]
            rel = f"{d / best_val * 100:.2f}%" + ("  ★" if cfg == best else "")
            print(f"{label if i == 0 else '':>18} {cfg:>8} {cr:>7.3f} {cd:>7.3f} "
                  f"{dmg:>7.2f} {atk:>7.2f} {d:>10.4f} {rel:>10}")
        print()

    print(f"  各配置在 {len(scenarios)} 个场景中的夺冠次数：{win_count}")

    print("""
【⚠ 结论与社区共识冲突 —— 先别急着相信模型】

  纯主词条模型给出的排序是 33311 > 43311 > 44111，且 33311 在全部
  五个场景里夺冠。但社区主流配置明确是 43311，33311 几乎无人讨论。

  当模型与大规模玩家实践长期冲突时，先假设模型缺了变量，而不是假设
  几百万玩家一起搞错了。逐一检查本模型的省略项：

    · 5 件套合鸣效果 —— 三种配置都能满足（5 槽位全同套装），不构成差异
    · 副词条 —— 与 COST 层无关，已在扫描中作为公共项处理
    · 属性伤害加成只对本属性生效 —— 主流角色伤害为单一属性，影响有限
    · **首位声骸技能** —— 模型完全没有计入。1 号位声骸提供主动技，
      而强力技能几乎全部挂在 BOSS 级（COST 4）声骸上，COST 3 的技能
      在伤害量级上不可同日而语。

  最后一项就是缺失的变量。33311 的首位只能放 COST 3，等于**主动放弃了
  一整块输出来源**，而这块输出根本没进上面的乘区计算。§2b 把它补上。
""")


def section_2b_echo_skill():
    banner("§2b  把首位声骸技能补进模型 —— 求 43311 反超的临界占比")

    print("""
【建模】设常规伤害（上表算出的乘区结果）为 D，首位声骸技能贡献的伤害为 K。

    总输出 = D + K

  43311 与 44111 的首位可放 COST 4（强技能，记 K₄）
  33311 的首位只能放 COST 3（弱技能，记 K₃）

  43311 反超 33311 的条件：
      D₄₃ + K₄  >  D₃₃ + K₃
      K₄ - K₃   >  D₃₃ - D₄₃

  把右边换算成"占常规伤害的百分比"，即可得到一个可与实际对照的门槛。
""")

    print(SUB)
    print(f"{'场景':>20} {'D(43311)':>10} {'D(33311)':>10} {'差额':>9} "
          f"{'技能需补足':>12}")
    print(SUB)

    scenarios = [
        ("无额外双爆",        0.00, 0.00),
        ("+15% CR / +30% CD", 0.15, 0.30),
        ("+30% CR / +60% CD", 0.30, 0.60),
        ("+45% CR / +90% CD", 0.45, 0.90),
        ("+60% CR / +120% CD", 0.60, 1.20),
    ]
    gaps = []
    for label, ce, cde in scenarios:
        d43 = total_dmg(*build_panel("43311", ce, cde))
        d33 = total_dmg(*build_panel("33311", ce, cde))
        need = (d33 - d43) / d43
        gaps.append(need)
        print(f"{label:>20} {d43:>10.4f} {d33:>10.4f} {d33 - d43:>9.4f} "
              f"{need * 100:>11.2f}%")

    print(f"""
  临界门槛区间：{min(gaps) * 100:.2f}% ~ {max(gaps) * 100:.2f}%，
  且随双爆副词条增多而**下降**（成型队只需 {gaps[-1] * 100:.2f}%）。

【★ 结论二（修正版）：43311 的正确性来自声骸技能，而不是主词条】

  只要 COST 4 首位声骸技能相对 COST 3 技能多贡献约 5% 的总输出，
  43311 就反超 33311。而 BOSS 级声骸技能（变身类、召唤类）的伤害占比
  实测普遍在 5%~15% 区间 [实测校验项]，**远高于这个门槛**。

  所以：
    · 社区共识 43311 是对的
    · 但流传的理由（"4C 主词条最强"）是错的 —— 主词条层面 33311 反而更优
    · 真实理由是首位声骸技能，一个**不在词条系统里**的因素

  这个案例说明了拆解装备系统时的一个常见陷阱：**把系统边界画在词条上**。
  声骸的价值由「主词条 + 副词条 + 套装 + 技能」四部分构成，只算前两项
  会得出一个自洽但错误的结论。而且错得很隐蔽 —— 模型内部逻辑完全正确，
  数字也算对了，只是边界画错了。

  ==> 我保留了这次错误的完整推导过程，因为它比一个正确结论更有价值：
      它演示了数值模型如何在自洽的情况下给出错误答案，以及怎样通过
      "与实践冲突"这个信号把缺失变量找出来。
""")

    print(SUB)
    print("【副产品：44111 为什么依然垫底】")
    print(SUB)
    print("""
  44111 同样能在首位放 COST 4，享有与 43311 相同的技能收益 K₄。
  因此上面的修正对它一视同仁，两者的差距仍完全由主词条决定 ——
  而 §2 已经算出 44111 在全部场景落后 43311 约 13%~15%。

  结论不变：**44111 是纯粹更差的选择**，它的存在只能用资产约束解释（§3）。
""")


