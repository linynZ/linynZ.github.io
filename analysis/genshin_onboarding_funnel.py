def section_2_forgetting():
    banner("§2  教学与首次应用的间隔 —— 一条可标定的设计判据")

    print("""
【模型】采用 Ebbinghaus 保留曲线的常用形式

    R(t) = exp(-t / S)

  R = 保留率，t = 教学后经过的时间，S = 记忆强度参数（单位同 t）。

  设计判据：教学项在**首次被要求应用**时，保留率不应低于阈值 R_min。
  由此可解出教学—应用的最大间隔

    t_max = -S · ln(R_min)

  S 需要按品类标定 [待实测]。下表给出几个量级供参照，
  说明这个判据怎么用，而非声称 S 就是这些值。
""")
    print(SUB)
    print(f"{'S(分钟)':>10} {'R_min=0.9':>12} {'R_min=0.8':>12} {'R_min=0.7':>12}")
    print(SUB)
    for S in (5, 10, 20, 30):
        row = [f"{-S * __import__('math').log(rm):.1f} 分" for rm in (0.9, 0.8, 0.7)]
        print(f"{S:>10} {row[0]:>12} {row[1]:>12} {row[2]:>12}")

    print("""
{0}
【★ 结论三：原神的"情境即教程"本质上是把 t 压到接近 0】
{0}

  原神几乎所有核心教学都绑定在"第一次必然发生的情境"上：
    · 遇到第一个坡 → 教攀爬 → **立刻就要爬**
    · 从高处落下 → 教滑翔翼 → **立刻就要滑**
    · 第一组史莱姆 → 教普攻 → **立刻就要打**

  在上面的模型里，这等价于令 t → 0，于是 R(t) → 1，
  遗忘曲线这一项**被彻底绕开了**。

  与之对比，传统 MMO 的"新手教程集中弹窗 + 之后自己摸索"是把 t 拉到
  几十分钟甚至更久，保留率按上表会掉到 0.3~0.5 —— 这正是那类教学
  "教了等于没教"的量化解释。

  ==> 所以"绑定式教学"的价值不在于它更不打扰玩家（那是副产品），
      而在于它把教学—应用间隔压到零，从根本上取消了遗忘损耗。
      这是一个可以直接迁移到任何教学设计的原则。

{0}
【推论：哪些教学项在原神里是"高风险"的】
{0}

  按这个判据审视正文 §3 教学埋点表，风险最高的是那些
  **教学与首次真正需要它之间隔了很久**的项：

    · 元素视野：教学时绑定任务节点，但玩家下一次真正需要它
      可能是几十分钟后的另一个任务 → t 大，保留率低
    · 任务界面 / 背包：首次教学是红点驱动的"看一眼"，
      真正需要熟练操作是在更晚 → t 大
    · 多角色切换：安柏入队时教，但若玩家不换人，
      首次真正应用可能推迟到很久以后 → t 不确定

  它们正是正文 §5.1 演示中被设定高流失假设的环节。注意这只是
  **先验一致性，不是交叉印证** —— 漏斗那一路的"点名"来自自设
  参数，两条路径并不独立。间隔判据的正确用法：在拿到流失数据
  之前为漏斗假设提供先验；待实录测得真实间隔后与实测流失分布
  对照，那才构成交叉印证（详见正文 §5.3 的 v1.1 修订说明）。
""".format(SUB))


def main():
    print("《原神》新手关卡拆解案 · 计算附录")
    print("⚠️ 本脚本参数为显式假设值，非实测数据 —— 详见文件头说明")
    print("复现：python genshin_onboarding_funnel.py")
    R = section_1_funnel()
    section_1b_target(R)
    section_2_forgetting()
    print("\n" + SEP)
    print("完")
    print(SEP)


if __name__ == "__main__":
    main()
