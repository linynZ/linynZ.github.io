"""
《原神》新手关卡拆解案 —— 留存漏斗敏感度与教学间隔判据
作者：赵鹏淦 (Penggan Zhao)

⚠️ 与本作品集另外三份数值向拆解案不同，本脚本的输入**不是公开的游戏数据**，
   而是一组**显式假设的参数**。原因很简单：新手关卡的分环节流失率是厂商
   核心内部数据，不可能公开，任何声称"实测得到"的数字都不可信。

   因此本脚本的价值在于**方法与结论形态**，不在具体数字：
     · 哪个环节该优先修 —— 这个结论对参数取值不敏感（§1）
     · 教学与首次应用的间隔上限 —— 给出判据形式，参数待标定（§2）

   把假设当数据用是数值分析里最容易犯也最难挽回的错误，故在此显式声明。

§1 留存漏斗的敏感度分析：纠正"优先修最早环节"这一常见产品直觉
§2 教学—应用间隔的遗忘曲线判据
"""

from math import exp

SEP = "=" * 78
SUB = "-" * 78


def banner(t):
    print("\n" + SEP)
    print(t)
    print(SEP)


# ---------------------------------------------------------------------------
# §1 留存漏斗敏感度
# ---------------------------------------------------------------------------
# 教学埋点序列（顺序即玩家经历顺序），p = 该环节流失率【全部为假设值】
FUNNEL = [
    ("开幕 CG（可跳过）",      0.05),
    ("性别选择 / 命名",        0.02),
    ("移动 / 视角教学",        0.03),
    ("首战：普攻",             0.06),
    ("元素战技 E",             0.04),
    ("攀爬 / 体力条",          0.08),
    ("滑翔翼（剧情锁）",       0.05),
    ("元素视野 + 任务界面",    0.12),
    ("安柏事件 / 多角色切换",  0.07),
    ("抵达蒙德城",             0.03),
]


def section_1_funnel():
    banner("§1  留存漏斗敏感度 —— 优先该修哪个环节？")

    print("""
【模型】玩家依次经过 n 个环节，各环节流失率 p_i，则通关总留存

    R = Π (1 - p_i)

  产品侧的常见直觉是"优先优化最早的环节，因为经过的人最多"。
  下面证明这个直觉**在相对留存的意义上是错的**。

【解析】对 R 求偏导：

    ∂R/∂p_i = -Π_{j≠i}(1-p_j) = -R / (1-p_i)

  这个结果与 i 的**位置无关** —— 只取决于该环节自身的 p_i。
  p_i 越大，敏感度越大。也就是说：

      ★ 优先该修的是流失率最高的环节，不是最早的环节。
""")

    print(SUB)
    print(f"{'#':>3} {'环节':>22} {'流失率':>8} {'累积到达':>10} "
          f"{'绝对流失':>10} {'敏感度':>10} {'修复收益':>10}")
    print(SUB)

    R = 1.0
    for p in FUNNEL:
        R *= (1 - p[1])

    reach = 1.0
    rows = []
    for i, (name, p) in enumerate(FUNNEL, 1):
        abs_loss = reach * p                 # 该环节的绝对流失占比
        sens = R / (1 - p)                   # |∂R/∂p_i|
        # 修复收益：把该环节流失率减半，总留存提升多少
        gain = R * ((1 - p / 2) / (1 - p)) - R
        rows.append((i, name, p, reach, abs_loss, sens, gain))
        print(f"{i:>3} {name:>22} {p:>8.1%} {reach:>10.1%} "
              f"{abs_loss:>10.1%} {sens:>10.4f} {gain:>+10.2%}")
        reach *= (1 - p)

    print(SUB)
    print(f"  最终通关留存 R = {R:.2%}")

    by_abs = max(rows, key=lambda r: r[4])
    by_gain = max(rows, key=lambda r: r[6])
    by_early = rows[0]

    print(f"""
{SUB}
【★ 结论一：三种排序给出三个不同的"最该修的环节"】
{SUB}

  按【最早】排序   → {by_early[1]}（流失率仅 {by_early[2]:.1%}）
  按【绝对流失】排 → {by_abs[1]}（吃掉 {by_abs[4]:.1%} 的总盘子）
  按【修复收益】排 → {by_gain[1]}（流失率减半可提升总留存 {by_gain[6]:+.2%}）

  后两者指向同一个环节，而"最早"指向另一个。这说明：
  **"越早的环节越重要"是一个错误的产品直觉。**
  它混淆了"经过的人多"与"损失的人多" —— 经过的人多但流失率低的环节，
  优化它的边际收益反而最小。

  正确的优先级 = 按流失率排序。注意它与"按绝对流失人数排序"
  一般**并不等价**：绝对流失 = 累积到达 × 流失率，早期环节因
  累积到达高而天然占优（反例：把 1 号环节流失率改成 9%，绝对
  流失最大的变成 1 号，但按敏感度最该修的仍是 12% 的
  「{by_gain[1]}」）。本例两种排序恰好一致，只因 8 号的流失率
  显著高于其余 —— 恰好一致不等于等价。
""")

    print(SUB)
    print("【必须说清楚：哪部分结论依赖假设参数，哪部分不依赖】")
    print(SUB)
    print("""
  这里容易做一个自欺欺人的"稳健性检验"：把所有 p 等比缩放，
  发现排序不变，然后宣称结论稳健。但等比缩放本来就保持相对大小，
  排序当然不变 —— 这种检验什么也没证明。我先写了这么一段，
  发现它是循环论证，删掉了。

  诚实的区分是这样的：

  【不依赖参数 —— 解析结果，永远成立】
     ∂R/∂p_i = -R/(1-p_i)，与位置 i 无关，随 p_i 单调递增。
     ==> "按流失率排序，而不是按位置排序" 这条**决策规则**是数学结论，
         无论真实流失率是多少都成立。

  【完全依赖参数 —— 没有真实数据就不能下结论】
     "元素视野 + 任务界面是最该修的环节" 这个**具体判断**，
     完全来自我假设它的流失率是 12%。换一组假设就会换一个答案。
     它在本文里只能作为**方法演示**，不能作为结论引用。

  实际工作里这个区分很关键：拿不到数据时，仍然可以先把决策规则
  确定下来，等埋点数据到位直接代入。反过来，一个会随参数翻转的判断，
  在拿到真实数据前根本不该被写进结论。

  ==> 本文凡涉及"具体哪个环节"的表述，一律标注为【假设演示】。
""")

    return R


def section_1b_target(R):
    banner("§1b  反推：要达到行业次留基准，各环节流失率的上限是多少")

    n = len(FUNNEL)
    print(f"""
  新手关卡通关率与次日留存不是同一指标，但前者是后者的上界
  （没通关的玩家几乎不会次日回来）。设行业次留目标为 D，
  且通关玩家的次留转化率为 c，则要求

      R × c ≥ D   ==>   R ≥ D / c

  在 n = {n} 个环节均匀分摊的情况下，单环节流失率上限为

      p_max = 1 - (D/c)^(1/n)
""")
    print(SUB)
    print(f"{'次留目标 D':>12} {'通关→次留 c':>14} {'所需 R':>10} {'单环节流失上限':>16}")
    print(SUB)
    for D in (0.30, 0.40, 0.50):
        for c in (0.7, 0.85):
            need_R = D / c
            if need_R >= 1:
                print(f"{D:>12.0%} {c:>14.0%} {'不可达':>10} {'—':>16}")
                continue
            p_max = 1 - need_R ** (1 / n)
            print(f"{D:>12.0%} {c:>14.0%} {need_R:>10.1%} {p_max:>15.2%}")

    print(f"""
{SUB}
【★ 结论二：环节数本身就是留存预算，教学项越多，单项容错越低】
{SUB}

  上表最有用的一列是最后一列。以次留 40%、转化率 85% 为例，
  单环节流失率必须压到约 {1 - (0.40 / 0.85) ** (1 / n):.1%} 以下 —— 这是一个相当苛刻的数字，
  意味着**每 {1 / (1 - (0.40 / 0.85) ** (1 / n)):.0f} 个走到该环节的玩家里最多只能流失 1 个**。

  更关键的推论：p_max 随环节数 n 增加而下降。
  也就是说，**每多加一个教学埋点，就摊薄了所有环节的容错预算**。

  这给出了新手关卡设计的一条硬约束，也解释了原神的两个做法：

  (1) **能合并的教学一定合并**。攀爬与体力条是一个环节而非两个，
      拾取与背包是一个环节而非两个 —— 不是偷懒，是在省留存预算。

  (2) **可错过的教学不占环节**。元素反应做成"可以完全不理解也能过"，
      它就不进入这条乘法链；靠后续重复暴露来补课，把教学成本
      从"必过关卡"转移到"长期渗透"。

  ==> 拆解新手关卡时，"教了多少东西"是个坏指标，
      "占用了几个必过环节"才是好指标。前者越多越显得内容丰富，
      后者越多留存越差 —— 两者方向相反，这也是新手关卡最反直觉的地方。
""")


